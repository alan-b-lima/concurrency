package main

import (
	"fmt"
	"strings"
	"unicode/utf8"
)

func Map(s string) (string, error) {
	var b strings.Builder

	for len(s) > 0 {
		before, after, ok := strings.Cut(s, "\n")
		if r := mapLine(&b, before); r != -1 {
			return "", fmt.Errorf("rune %+q are not mapped\n", r)
		}
		if ok {
			b.WriteByte('\n')
		}

		s = after
	}

	s = b.String()
	return s[:len(s)-1], nil
}

func mapLine(b *strings.Builder, s string) rune {
	_, w := utf8.DecodeLastRuneInString(s)
	last := len(s) - w

	for l := range runeheight {
		for i, r := range s {
			ls, in := runemap[r]
			if !in {
				return r
			}

			b.WriteString(ls[l])
			if i != last {
				b.WriteByte(' ')
			} else {
				b.WriteByte('\n')
			}
		}
	}

	return -1
}

